// The squarer only sees the top 10 bits of x2, as a distance from the middle of the segment.
static inline int32_t Square(u32 x2) {
	const int32_t t = std::abs(int32_t(x2 >> 6) - 512);
	return (t * t + 255) >> 8;
}

// The untruncated result, in ulps of 2^(seg.e - 150).
static inline int32_t Interp(const VFPUSegment &seg, u32 x2) {
	return seg.c0 + int32_t(((int64_t)seg.m * x2) >> 17) + ((seg.n * Square(x2)) >> 9);
}

// Float bits of a result in [2^(e-127), 2^(e-126)], truncated to 22 bits. The top of that range
// carries into the exponent, which gives exactly the next power of two.
static inline u32 InterpBits(const VFPUSegment *segments, u32 index) {
	const VFPUSegment &seg = segments[index >> 16];
	return ((u32(seg.e - 1) << 23) + u32(Interp(seg, index & 0xFFFF))) & ~3u;
}

// Sine of a quarter-wave angle arg in [0, 2^23] (0 to pi/2), in fixed point with 28 fraction bits.
// The segments are indexed from the top of the quarter wave. Each has its own exponent, and its
// results are truncated to 4 of its ulps even where they fall into a lower binade.
static inline u32 SinFixed(u32 arg) {
	if (arg == 0u) return 0u;
	if (arg == 0x00800000u) return 0x10000000u;
	const u32 y = 0x00800000u - arg;
	const VFPUSegment &seg = vfpu_sin_segments[y >> 16];
	const u32 v = u32(Interp(seg, y & 0xFFFF)) & ~3u;
	return seg.e >= 122 ? v << (seg.e - 122) : v >> (122 - seg.e);
}

// Reduces an angle in quarter turns (the VFPU's unit) to a half turn, in units of 2^-23 quarter
// turns. Sets *odd for an odd half turn, where the sine changes sign. Returns false for inf and NaN.
static inline bool SinReduce(u32 bits, u32 *angle, bool *odd) {
	const u32 exponent = (bits >> 23) & 0xFFu;
	u32 significand = (bits & 0x007FFFFFu) | 0x00800000u;
	if (exponent == 0xFFu) return false;
	if (exponent < 0x7Fu) {
		if (exponent < 0x7Fu - 23u) significand = 0u;
		else significand >>= (0x7F - exponent);
	} else if (exponent > 0x7Fu) {
		// There is weirdness for large exponents.
		if (exponent - 0x7Fu >= 25u && exponent - 0x7Fu < 32u) significand = 0u;
		else if ((exponent & 0x9Fu) == 0x9Fu) significand = 0u;
		else significand <<= ((exponent - 0x7Fu) & 31);
	}
	*odd = (significand >> 24) & 1;
	*angle = significand & 0x00FFFFFFu;
	return true;
}

static inline int Clz64NonZero(u64 v) {
	return (v >> 32) != 0 ? (int)Clz32NonZero(u32(v >> 32)) : 32 + (int)Clz32NonZero(u32(v));
}

// Float bits of v * 2^-fracBits, with the sign bit set if negative (also for zero). v has to fit
// in a float's significand, which every result here does, since the VFPU keeps 22 bits.
static inline u32 FixedToBits(u64 v, int fracBits, bool negative) {
	const u32 sign = negative ? 0x80000000u : 0u;
	if (v == 0) return sign;
	const int top = 63 - Clz64NonZero(v);
	const u64 significand = top <= 23 ? v << (23 - top) : v >> (top - 23);
	return sign + (u32(top - fracBits + 127) << 23) + (u32(significand) & 0x007FFFFFu);
}

static inline u32 SinFromReduced(u32 angle, bool negate) {
	if (angle > 0x00800000u) angle = 0x01000000u - angle;
	return FixedToBits(SinFixed(angle), 28, negate);
}

static inline u32 CosFromReduced(u32 angle, bool negate) {
	if (angle >= 0x00800000u) {
		angle = 0x01000000u - angle;
		negate = !negate;
	}
	return FixedToBits(SinFixed(0x00800000u - angle), 28, negate);
}

u32 Sin(u32 bits) {
	u32 angle;
	bool odd;
	if (!SinReduce(bits, &angle, &odd)) return (bits & 0x80000000u) ^ 0x7F800001u;
	return SinFromReduced(angle, ((bits >> 31) != 0) != odd);
}

u32 Cos(u32 bits) {
	u32 angle;
	bool odd;
	if (!SinReduce(bits, &angle, &odd)) return 0x7F800001u;
	return CosFromReduced(angle, odd);
}

void SinCos(u32 bits, u32 *s, u32 *c) {
	u32 angle;
	bool odd;
	if (!SinReduce(bits, &angle, &odd)) {
		*s = (bits & 0x80000000u) ^ 0x7F800001u;
		*c = 0x7F800001u;
	} else {
		*s = SinFromReduced(angle, ((bits >> 31) != 0) != odd);
		*c = CosFromReduced(angle, odd);
	}
}

// Fast-path tables for rcp/rsqrt/sqrt: k is c0 plus the exponent bits of the result.
struct FastSegment {
	u32 k;
	int32_t m;
	int32_t n;
};

struct FastTable {
	FastSegment seg[128];
};

static constexpr FastTable MakeFastTable(const VFPUSegment (&segments)[128], int bias) {
	FastTable table{};
	for (int i = 0; i < 128; i++) {
		const VFPUSegment &s = segments[i];
		table.seg[i] = {u32(s.c0) + (u32(s.e - 1 + bias) << 23), s.m, s.n};
	}
	return table;
}

static constexpr FastTable kRcpFast = MakeFastTable(vfpu_rcp_segments, 127);
static constexpr FastTable kRsqrtFast = MakeFastTable(vfpu_rsqrt_segments, 64);
static constexpr FastTable kSqrtFast = MakeFastTable(vfpu_sqrt_segments, -64);

// rcp: w = bits, result (k - (bits & 0xFF800000) + linear + square) & ~3.
// rsqrt/sqrt: w = (bits + 0x00800000) >> 1, result (k -/+ (w & 0x7F800000) + linear + square) & ~3.
// linear = (m * x2) >> 17 and square = (n * Square(x2)) >> 9, with x2 the low 16 bits of w.
static inline u32 FastInterp(const FastTable &table, u32 w, u32 exponent) {
	const FastSegment &seg = table.seg[(w >> 16) & 0x7F];
	const u32 x2 = w & 0xFFFF;
	const u32 linear = u32(((int64_t)seg.m * x2) >> 17);
	const u32 square = u32((seg.n * Square(x2)) >> 9);
	return (seg.k + exponent + linear + square) & ~3u;
}

// |x| in [2^-126, 2^126].
static inline bool RcpIsFast(u32 bits) { return (bits << 1) - 0x01000000u <= 0xFC000000u; }
// Positive, normal and finite.
static inline bool SqrtIsFast(u32 bits) { return bits - 0x00800000u < 0x7F000000u; }

u32 Sqrt(u32 bits) {
	if (SqrtIsFast(bits)) {
		const u32 w = (bits + 0x00800000u) >> 1;
		return FastInterp(kSqrtFast, w, w & 0x7F800000u);
	}
	// Zero and denormals give +0, whatever the sign.
	if ((bits & 0x7FFFFFFFu) < 0x00800000u) return 0;
	// Negatives and NaN give NaN, inf gives inf.
	return bits == 0x7F800000u ? 0x7F800000u : 0x7F800001u;
}

u32 Rsqrt(u32 bits) {
	if (SqrtIsFast(bits)) {
		const u32 w = (bits + 0x00800000u) >> 1;
		return FastInterp(kRsqrtFast, w, 0u - (w & 0x7F800000u));
	}
	// Zero and denormals give inf of the same sign.
	if ((bits & 0x7FFFFFFFu) < 0x00800000u) return (bits & 0x80000000u) | 0x7F800000u;
	// Negatives give -NaN, NaN gives NaN and inf gives 0.
	return (bits >> 31) ? 0xFF800001u : (bits > 0x7F800000u ? 0x7F800001u : 0u);
}

// asin(x) * 2/pi in fixed point with 30 fraction bits, for x in [0, 1] as 23-bit fixed point.
static inline u32 AsinFixed(u32 x) {
	if (x == 0u) return 0u;
	if (x == 1u << 23) return 1u << 30;
	const VFPUSegment &seg = vfpu_asin_segments[x >> 16];
	// The first segment is linear, and keeps the 2^-30 step of the fixed-point output.
	const u32 v = u32(Interp(seg, x & 0xFFFF)) & ((x >> 16) == 0 ? ~1u : ~3u);
	return seg.e >= 120 ? v << (seg.e - 120) : v >> (120 - seg.e);
}

u32 Asin(u32 bits) {
	const u32 sign = bits & 0x80000000u;
	const u32 abs = bits & 0x7FFFFFFFu;
	if (abs > 0x3F800000u) return 0x7F800001u ^ sign;
	// |x| * 2^23, truncated. Anything below 2^-23, denormals included, gives 0.
	const int e = int(abs >> 23);
	const u32 significand = (abs & 0x007FFFFFu) | 0x00800000u;
	const u32 fixed = e < 104 ? 0 : significand >> (127 - e);
	return FixedToBits(AsinFixed(fixed), 30, sign != 0);
}

u32 Exp2(u32 bits) {
	const u32 abs = bits & 0x7FFFFFFFu;
	const bool negative = (bits >> 31) != 0;
	// Denormals are treated as 0.
	if (abs <= 0x007FFFFFu) return 0x3F800000u;
	// NaN gets NaN.
	if (abs > 0x7F800000u) return 0x7F800001u;
	// -126 and below get 0 (exp2(-126) is the smallest normal, but -126 gives +0).
	if (negative && abs >= 0x42FC0000u) return 0;
	// 128 and above get infinity.
	if (!negative && abs >= 0x43000000u) return 0x7F800000u;
	// x * 2^23 truncated toward zero, and one less for a negative x.
	const int e = int(abs >> 23);
	const u32 significand = (abs & 0x007FFFFFu) | 0x00800000u;
	int32_t fixed = e >= 127 ? int32_t(significand << (e - 127)) : (e < 104 ? 0 : int32_t(significand >> (127 - e)));
	if (negative) fixed = -fixed - 1;
	// The fraction's exp2 is in [1, 2), so its significand bits are the offset from 1.0.
	const u32 frac = u32(fixed) & 0x007FFFFFu;
	const u32 significandBits = frac == 0 ? 0 : InterpBits(vfpu_exp2_segments, frac) - 0x3F800000u;
	return 0x3F800000u + (u32(fixed) & 0xFF800000u) + significandBits;
}

u32 Rexp2(u32 bits) { return Exp2(bits ^ 0x80000000u); }

u32 Log2(u32 bits) {
	// Denormals (and zeroes) get -inf.
	if ((bits & 0x7FFFFFFFu) <= 0x007FFFFFu) return 0xFF800000u;
	// Other negatives get NaN.
	if (bits & 0x80000000u) return 0x7F800001u;
	// NaN gets NaN, +inf gets +inf.
	if ((bits >> 23) == 255u) return 0x7F800000u + ((bits & 0x007FFFFFu) != 0);
	// The result is exponent + log2(1.mantissa), truncated toward zero to 22 significant bits: a
	// step of 2^-22 for exponents 0 and 1, twice that for each doubling of the exponent after that,
	// and 2^-15 for every negative exponent (level d = 7). Where the step is coarser, the datapath
	// drops coefficient bits too: m to the step, |n| to 2^d, and c0 takes the part of the squared
	// term that was dropped, at the edge of the segment.
	const int32_t exponent = int32_t(bits >> 23) - 127;
	const u32 index = bits & 0x007FFFFFu;
	const int d = exponent < 0 ? 7 : exponent < 2 ? 0 : 31 - (int)Clz32NonZero(u32(exponent));
	const int32_t p = 1 << d;
	const int64_t step = int64_t(4 << d) << 17;
	const VFPUSegment &seg = vfpu_log2_segments[index >> 16];
	const u32 x2 = index & 0xFFFF;
	const int32_t n = seg.n < 0 ? -(-seg.n & ~(p - 1)) : (seg.n & ~(p - 1));
	const int32_t c0 = (seg.c0 + 2 * (seg.n - n)) & ~(p - 1);
	const int32_t square = ((n * Square(x2)) >> 9) & ~(p - 1);
	const int64_t m = seg.m & ~((4 << d) - 1);
	// In units of 2^-41.
	const int64_t y = (int64_t(c0 + square) << 17) + m * x2;
	const int64_t frac = exponent >= 0 ? (y & ~(step - 1)) : -(-y & ~(step - 1));
	// A negative sum truncated to zero keeps its sign.
	const int64_t sum = (int64_t(exponent) << 41) + frac;
	return FixedToBits(u64(sum < 0 ? -sum : sum), 41, exponent < 0);
}

u32 Rcp(u32 bits) {
	if (RcpIsFast(bits)) return FastInterp(kRcpFast, bits, 0u - (bits & 0xFF800000u));
	// Zero and denormals give inf, NaN gives NaN and the rest 0, all with the sign of x.
	const u32 abs = bits & 0x7FFFFFFFu;
	return (bits & 0x80000000u) ^ (abs < 0x00800000u ? 0x7F800000u : (abs > 0x7F800000u ? 0x7F800001u : 0u));
}

// The hardware dot product (PPSSPP vfpu_dot_reference, see
// https://github.com/hrydgard/ppsspp/issues/21070): products in extra precision with
// round-to-odd, aligned by truncation, summed exactly, then rounded to nearest even.
u32 DotBits(const u32 a[4], const u32 b[4]) {
	const int EXTRA_BITS = 2;
	const u32 I = u32(1) << 23, J = u32(1) << (23 - EXTRA_BITS);
	int32_t s[4], e[4], ehi = -2 * 127;
	u32 p[4];
	int32_t val = 0;
	int has_inf = 0;
	for (int i = 0; i < 4; i++) {
		const u32 x = a[i], y = b[i];
		const int32_t ex = int32_t((x >> 23) & 255), ey = int32_t((y >> 23) & 255);
		const u32 mx = x & (I - 1), my = y & (I - 1);
		if (ex == 255 || ey == 255) {
			const int sgn = ((x ^ y) >> 31) ? -1 : +1;
			if (ex == 255 && mx != 0) return 0x7F800001u;       // x = nan
			if (ey == 255 && my != 0) return 0x7F800001u;       // y = nan
			if (ex == 255 && ey == 0) return 0x7F800001u;       // inf * 0 = nan
			if (ey == 255 && ex == 0) return 0x7F800001u;       // 0 * inf = nan
			if (has_inf && has_inf != sgn) return 0x7F800001u;  // inf - inf = nan
			has_inf = sgn;
		}
		s[i] = int32_t((x ^ y) >> 31);
		e[i] = int32_t(ex + ey) - 2 * 127;
		const u64 v = u64(I + mx) * u64(I + my);
		p[i] = u32(v >> (23 - EXTRA_BITS));
		if (v & (J - 1)) p[i] |= 1;  // round-to-odd
		if (!(ex && ey)) {
			// Subnormals are zero.
			e[i] = -2 * 127;
			p[i] = 0;
		}
		if (e[i] > ehi) ehi = e[i];
	}
	if (has_inf) return has_inf < 0 ? 0xFF800000u : 0x7F800000u;
	// Align to the largest exponent by truncation; the sum is then exact.
	for (int i = 0; i < 4; i++) {
		int32_t d = ehi - e[i];
		if (d > 28) d = 28;
		const u32 v = p[i] >> d;
		val += (s[i] ? -1 : +1) * int32_t(v);
	}
	u32 m = u32(val < 0 ? -val : +val);
	// Drop the extra precision (round-to-zero), then normalize with round-to-nearest-even.
	m >>= EXTRA_BITS;
	if (m != 0) {
		const int shift = 8 - int(Clz32NonZero(m));
		ehi += shift;
		if (shift > 0) {
			const u32 r = u32(1) << (shift - 1);
			m = (m >> shift) + ((m & (2 * r - 1)) + ((m >> shift) & 1) > r);
			if (m >= 2 * I) {
				m >>= 1;
				ehi += 1;
			}
		}
		if (shift < 0) m = m << -shift;
	} else {
		ehi = -128;
	}
	if (ehi <= -127) {
		// Subnormals are zero.
		ehi = -127;
		m = 0;
	}
	if (ehi >= +128) {
		// Infinity.
		ehi = +128;
		m = 0;
	}
	return (u32(val < 0) << 31) | (u32(ehi + 127) << 23) | u32(m & 0x007FFFFF);
}

// ---- Random number generator (https://github.com/hrydgard/ppsspp/issues/16946) ----

void RndInit(u32 seed, u32 *rcx) {
	for (int i = 0; i < 8; ++i) {
		rcx[i] = 0x3F800000u |                         // 1.0f mask.
		         ((seed >> ((i / 4) * 16)) & 0xFFFFu) |  // lower or upper half of the seed.
		         (((seed >> (4 * i)) & 0xF) << 16);      // remaining nibble.
	}
}

u32 RndGenerate(u32 *rcx) {
	// The state is five 32-bit parts spread over the eight registers.
	u32 A = (rcx[0] & 0xFFFFu) | (rcx[4] << 16);
	u32 B = (rcx[1] & 0xFFFFu) | (rcx[5] << 16);
	u32 C = (rcx[2] & 0xFFFFu) | (rcx[6] << 16);
	u32 D = (rcx[3] & 0xFFFFu) | (rcx[7] << 16);
	u32 E = (((rcx[0] >> 16) & 0xF) << 0) | (((rcx[1] >> 16) & 0xF) << 4) | (((rcx[2] >> 16) & 0xF) << 8) |
	        (((rcx[3] >> 16) & 0xF) << 12) | (((rcx[4] >> 16) & 0xF) << 16) | (((rcx[5] >> 16) & 0xF) << 20) |
	        (((rcx[6] >> 16) & 0xF) << 24) | (((rcx[7] >> 16) & 0xF) << 28);
	// LCG with classic parameters.
	A = 69069u * A + 1u;
	// Xorshift (Marsaglia's "xor" variant).
	B ^= B << 13;
	B ^= B >> 17;
	B ^= B << 5;
	// A Pell-like sequence with an occasional increment (E).
	const u32 t = 2u * D + C + E;
	E = u32((u64(C) + u64(D >> 1) + u64(E)) >> 32);
	C = D;
	D = t;
	rcx[0] = 0x3F800000u | (((E >> 0) & 0xF) << 16) | (A & 0xFFFFu);
	rcx[1] = 0x3F800000u | (((E >> 4) & 0xF) << 16) | (B & 0xFFFFu);
	rcx[2] = 0x3F800000u | (((E >> 8) & 0xF) << 16) | (C & 0xFFFFu);
	rcx[3] = 0x3F800000u | (((E >> 12) & 0xF) << 16) | (D & 0xFFFFu);
	rcx[4] = 0x3F800000u | (((E >> 16) & 0xF) << 16) | (A >> 16);
	rcx[5] = 0x3F800000u | (((E >> 20) & 0xF) << 16) | (B >> 16);
	rcx[6] = 0x3F800000u | (((E >> 24) & 0xF) << 16) | (C >> 16);
	rcx[7] = 0x3F800000u | (((E >> 28) & 0xF) << 16) | (D >> 16);
	return A + B + D;
}

// ---- Half floats (vh2f/vf2h), bit-exact to the hardware (cpu/vfpu/specials) ----

u32 H2F(u16 h) {
	const u32 sign = (u32)(h & 0x8000) << 16;
	const u32 exp = (h >> 10) & 0x1F;
	const u32 mant = h & 0x3FF;
	// Zero and subnormal halves both give a signed zero.
	if (exp == 0) return sign;
	// Inf/NaN: the mantissa bits stay where they are, not shifted into place.
	if (exp == 31) return sign | 0x7F800000 | mant;
	return sign | ((exp + 112) << 23) | (mant << 13);
}

u16 F2H(u32 f) {
	const u16 sign = (u16)((f >> 16) & 0x8000);
	const u32 exp = (f >> 23) & 0xFF;
	const u32 mant = f & 0x7FFFFF;
	// Inf/NaN: the low ten mantissa bits carry over, so a NaN with those clear becomes inf.
	if (exp == 255) return sign | 0x7C00 | (u16)(mant & 0x3FF);
	// Below 2^-14: no subnormal halves, signed zero.
	if (exp < 113) return sign;
	// 65536 and up: inf. Nothing rounds up to it, since the mantissa is truncated.
	if (exp >= 143) return sign | 0x7C00;
	return sign | (u16)((exp - 112) << 10) | (u16)(mant >> 13);
}

