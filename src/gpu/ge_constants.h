inline GEPrimitiveType PatchPrimToPrim(int type) {
	switch (type) {
	case GE_PATCHPRIM_TRIANGLES: return GE_PRIM_TRIANGLES;
	case GE_PATCHPRIM_LINES: return GE_PRIM_LINES;
	default: return GE_PRIM_POINTS;
	}
}

