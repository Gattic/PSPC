TEST(fs_inflate_zlib_vectors) {
	CHECK(InflatesTo(kDeflateText, sizeof(kDeflateText), fstest::Text(1, 4000)));
	CHECK(InflatesTo(kDeflateBinary, sizeof(kDeflateBinary), fstest::Binary(7, 3000)));
	CHECK(InflatesTo(kDeflateFlushed, sizeof(kDeflateFlushed), fstest::Text(3, 2500)));
	CHECK(InflatesTo(kDeflateHuffOnly, sizeof(kDeflateHuffOnly), fstest::Binary(11, 1500)));

	std::vector<u8> want = fstest::Text(5, 1200);
	std::vector<u8> out(1200);
	CHECK(IsZlibHeader(kZlibText, sizeof(kZlibText)));
	CHECK_EQ(InflateZlib(kZlibText, sizeof(kZlibText), out.data(), out.size()), (s64)1200);
	CHECK(out == want);
	// A wrong Adler-32 is caught.
	std::vector<u8> bad(kZlibText, kZlibText + sizeof(kZlibText));
	bad.back() ^= 1;
	CHECK_EQ(InflateZlib(bad.data(), bad.size(), out.data(), out.size()), (s64)-1);
}

TEST(fs_inflate_rejects_bad_input) {
	std::vector<u8> want = fstest::Text(1, 4000);
	std::vector<u8> out(4000);
	// Output too small.
	CHECK_EQ(InflateRaw(kDeflateText, sizeof(kDeflateText), out.data(), 3999), (s64)-1);
	// Truncated streams.
	for (size_t cut : {(size_t)0, (size_t)1, (size_t)10, sizeof(kDeflateText) / 2, sizeof(kDeflateText) - 1}) {
		CHECK_EQ(InflateRaw(kDeflateText, cut, out.data(), out.size()), (s64)-1);
	}
	// Reserved block type 3.
	const u8 type3[] = {0x07, 0x00};
	CHECK_EQ(InflateRaw(type3, sizeof(type3), out.data(), out.size()), (s64)-1);
	// Stored block with a bad NLEN.
	const u8 storedBad[] = {0x01, 0x03, 0x00, 0xFC, 0xFE, 'a', 'b', 'c'};
	CHECK_EQ(InflateRaw(storedBad, sizeof(storedBad), out.data(), out.size()), (s64)-1);
	const u8 storedOk[] = {0x01, 0x03, 0x00, 0xFC, 0xFF, 'a', 'b', 'c'};
	CHECK_EQ(InflateRaw(storedOk, sizeof(storedOk), out.data(), out.size()), (s64)3);
	CHECK(!memcmp(out.data(), "abc", 3));
	// Distance reaching before the start of the output: fixed block, match (len 3, dist 1) first.
	fstest::BitWriter w;
	w.Put(1, 1);
	w.Put(1, 2);
	fstest::PutFixedMatch(w, 3, 1);
	fstest::PutFixedLit(w, 256);
	w.AlignByte();
	CHECK_EQ(InflateRaw(w.out.data(), w.out.size(), out.data(), out.size()), (s64)-1);
	// Random garbage never crashes or overruns.
	fstest::Lcg r(99);
	for (int i = 0; i < 300; i++) {
		std::vector<u8> junk(1 + r.Next() % 200);
		for (u8 &b : junk) b = (u8)r.Next();
		std::vector<u8> small(256);
		s64 n = InflateRaw(junk.data(), junk.size(), small.data(), small.size());
		CHECK(n >= -1 && n <= 256);
	}
}

TEST(fs_inflate_test_encoder_roundtrip) {
	for (u32 seed = 1; seed <= 6; seed++) {
		std::vector<u8> data = seed % 2 ? fstest::Text(seed, 9000 + seed * 777) : fstest::Binary(seed, 9000 + seed * 777);
		for (bool mix : {false, true}) {
			std::vector<u8> comp = fstest::Deflate(data.data(), data.size(), mix, 1000 + seed * 100);
			CHECK(comp.size() < data.size() + data.size() / 8 + 64);
			std::vector<u8> out(data.size());
			size_t used = 0;
			CHECK_EQ(InflateRaw(comp.data(), comp.size(), out.data(), out.size(), &used), (s64)data.size());
			CHECK_EQ(used, comp.size());
			CHECK(out == data);
			std::vector<u8> z = fstest::ZlibWrap(comp, data.data(), data.size());
			CHECK_EQ(InflateZlib(z.data(), z.size(), out.data(), out.size()), (s64)data.size());
		}
	}
	// Empty input still makes a valid stream.
	std::vector<u8> empty = fstest::Deflate(nullptr, 0);
	u8 dummy[4];
	CHECK_EQ(InflateRaw(empty.data(), empty.size(), dummy, sizeof(dummy)), (s64)0);
}

TEST(fs_lz4_blocks) {
	// Hand-made block: literals "abc", then a match of offset 3, length 9 (overlapping copy),
	// then the closing literals "xyz12".
	const u8 block[] = {0x35, 'a', 'b', 'c', 0x03, 0x00, 0x50, 'x', 'y', 'z', '1', '2'};
	u8 out[64];
	CHECK_EQ(Lz4DecompressBlock(block, sizeof(block), out, 17), (s64)17);
	CHECK(!memcmp(out, "abcabcabcabcxyz12", 17));
	// Trailing padding after the last sequence is ignored once the output is full.
	u8 padded[sizeof(block) + 8] = {};
	memcpy(padded, block, sizeof(block));
	CHECK_EQ(Lz4DecompressBlock(padded, sizeof(padded), out, 17), (s64)17);
	// Corrupt offsets and overflows fail.
	const u8 zeroOffset[] = {0x10, 'a', 0x00, 0x00, 0x00};
	CHECK_EQ(Lz4DecompressBlock(zeroOffset, sizeof(zeroOffset), out, sizeof(out)), (s64)-1);
	const u8 farOffset[] = {0x10, 'a', 0x05, 0x00, 0x00};
	CHECK_EQ(Lz4DecompressBlock(farOffset, sizeof(farOffset), out, sizeof(out)), (s64)-1);
	CHECK_EQ(Lz4DecompressBlock(block, sizeof(block), out, 10), (s64)-1);
	// Round trips through the test encoder, including long literal and match runs.
	for (u32 seed = 1; seed <= 6; seed++) {
		std::vector<u8> data = seed % 2 ? fstest::Text(seed, 5000 * seed) : fstest::Binary(seed, 5000 * seed);
		if (seed == 6) {
			data.insert(data.end(), 3000, 'Z');
		}
		std::vector<u8> comp = fstest::Lz4Compress(data.data(), data.size());
		std::vector<u8> back(data.size());
		CHECK_EQ(Lz4DecompressBlock(comp.data(), comp.size(), back.data(), back.size()), (s64)data.size());
		CHECK(back == data);
	}
	fstest::Lcg r(5);
	for (int i = 0; i < 300; i++) {
		std::vector<u8> junk(1 + r.Next() % 100);
		for (u8 &b : junk) b = (u8)r.Next();
		s64 n = Lz4DecompressBlock(junk.data(), junk.size(), out, sizeof(out));
		CHECK(n >= -1 && n <= (s64)sizeof(out));
	}
}
