bool InflatesTo(const u8 *in, size_t len, const std::vector<u8> &want) {
	std::vector<u8> out(want.size() + 64, 0xEE);
	size_t used = 0;
	s64 n = InflateRaw(in, len, out.data(), out.size(), &used);
	return n == (s64)want.size() && used == len && memcmp(out.data(), want.data(), want.size()) == 0;
}

