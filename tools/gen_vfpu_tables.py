"""Copy the VFPU interpolator coefficient tables from PPSSPP into src/allegrex/vfpu_math.cpp.

PPSSPP keeps the tables for its bit-exact vrcp/vrsq/vsqrt/vexp2/vlog2/vsin/vasin in
Core/MIPS/MIPSVFPUUtils.cpp (struct VFPUSegment plus seven 128-entry arrays). This script copies
that block verbatim between the "BEGIN PPSSPP TABLES" / "END PPSSPP TABLES" markers (or replaces an
"@@TABLES@@" placeholder), so nothing is loaded at run time.

Usage: python -I tools/gen_vfpu_tables.py [path/to/ppsspp]
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BEGIN = "// BEGIN PPSSPP TABLES (generated by tools/gen_vfpu_tables.py, do not edit)"
END = "// END PPSSPP TABLES"
TABLES = ["rcp", "rsqrt", "sqrt", "exp2", "log2", "sin", "asin"]


def extract(src):
	start = src.index("struct VFPUSegment {")
	# The block ends with the last table's closing "};".
	last = src.index("vfpu_asin_segments[128] = {")
	end = src.index("};", last) + 2
	block = src[start:end]
	for name in TABLES:
		m = re.search(r"vfpu_%s_segments\[128\] = \{(.*?)\};" % name, block, re.S)
		if not m:
			raise SystemExit("table %s not found" % name)
		entries = re.findall(r"\{[^{}]*\}", m.group(1))
		if len(entries) != 128:
			raise SystemExit("table %s has %d entries" % (name, len(entries)))
	return block


def main():
	ppsspp = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "reference", "ppsspp")
	with open(os.path.join(ppsspp, "Core", "MIPS", "MIPSVFPUUtils.cpp"), encoding="utf-8") as f:
		block = extract(f.read().replace("\r\n", "\n"))
	dst = os.path.join(ROOT, "src", "allegrex", "vfpu_math.cpp")
	with open(dst, encoding="utf-8", newline="") as f:
		text = f.read()
	new_block = BEGIN + "\n" + block + "\n" + END
	if "@@TABLES@@" in text:
		text = text.replace("@@TABLES@@", new_block)
	else:
		a = text.index(BEGIN)
		b = text.index(END) + len(END)
		text = text[:a] + new_block + text[b:]
	with open(dst, "w", encoding="utf-8", newline="") as f:
		f.write(text)
	print("wrote", dst)


if __name__ == "__main__":
	main()
