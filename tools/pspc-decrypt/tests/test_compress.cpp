static int DecodeKl4e(const Bytes &stream, Bytes *out, size_t capacity) {
	bool kl3e = false;
	if (!IsKL4EMagic(stream.data(), stream.size(), &kl3e)) {
		return -1;
	}
	out->assign(capacity, 0);
	const u8 *end = nullptr;
	const int n = DecompressKL4E(out->data(), (int)capacity, stream.data() + 4, stream.size() - 4, &end, kl3e);
	if (n >= 0) {
		out->resize(n);
	}
	return n;
}

TEST(kl4e_literal_roundtrip) {
	for (int variant = 0; variant < 40; variant++) {
		const u8 flags = (u8)((variant * 13) & 0x1F);  // every shift and probability seed
		const bool kl3e = (variant & 1) != 0;
		const Bytes data = variant % 3 ? PseudoRandom(1 + variant * 97, variant) : GenText(1 + variant * 101);
		const Bytes stream = Kl4eEncodeLiterals(data, flags, kl3e);
		Bytes out;
		CHECK_EQ(DecodeKl4e(stream, &out, data.size() + 1), (int)data.size());
		CHECK(out == data);
		// The firmware-derived decoder agrees.
		Bytes ref(data.size() + 0x1000, 0);
		Bytes streamCopy = stream;
		CHECK_EQ(decompress_kle(ref.data(), (int)ref.size(), streamCopy.data() + 4, nullptr, kl3e ? 0 : 1), (int)data.size());
		CHECK(memcmp(ref.data(), data.data(), data.size()) == 0);
		// And so does the generic path the module decoder uses.
		Bytes viaAny;
		std::string method, error;
		size_t consumed = 0;
		CHECK(DecompressAny(stream.data(), stream.size(), data.size(), &viaAny, &method, &consumed, &error));
		CHECK(viaAny == data);
		CHECK_EQ(method, std::string(kl3e ? "KL3E" : "KL4E"));
	}
	// Too small an output buffer is an error, not an overrun.
	const Bytes data = PseudoRandom(500, 1);
	Bytes out;
	CHECK_EQ(DecodeKl4e(Kl4eEncodeLiterals(data, 0), &out, 100), KL4E_ERROR_INVALID_SIZE);
}

TEST(kl4e_stored_stream) {
	const Bytes data = PseudoRandom(77, 3);
	Bytes stream = { 'K', 'L', '4', 'E', 0x80, 0, 0, 0, 77 };
	stream.insert(stream.end(), data.begin(), data.end());
	Bytes out;
	CHECK_EQ(DecodeKl4e(stream, &out, 78), 77);
	CHECK(out == data);
	// A stored payload that exactly fills the buffer is rejected, as on hardware.
	CHECK_EQ(DecodeKl4e(stream, &out, 77), KL4E_ERROR_INVALID_SIZE);
}

// Random streams through both decoders: every literal, match, distance and error path the
// format has gets exercised, and both must produce the same bytes and the same result. A run of
// literals first gives the matches that follow real history to copy from.
TEST(kl4e_differential_vs_firmware_port) {
	int compared = 0, ended = 0;
	long long produced = 0;
	const Bytes history = GenText(1500);
	for (u32 seed = 1; seed <= 3000; seed++) {
		const bool kl4e = (seed & 1) != 0;
		Bytes input;
		if (seed % 3 == 0) {
			input = PseudoRandom(2048, seed);
			input[0] &= 0x7F;  // compressed, not stored
		} else {
			const Bytes prefix = Kl4eEncodeLiterals(Bytes(history.begin(), history.begin() + (seed % 1400) + 1), (u8)(seed & 0x1F), !kl4e, false);
			input.assign(prefix.begin() + 4, prefix.end());
			const Bytes tail = PseudoRandom(8 + seed % 200, seed);
			input.insert(input.end(), tail.begin(), tail.end());
		}
		// Zero padding ends any stream quickly (all-ones bits are the end marker), so the
		// reference decoder, which doesn't bound its reads, stays inside the buffer.
		input.resize(input.size() + 0x10000, 0);
		const int capacity = 1 << 18;
		Bytes ours(capacity, 0);
		const u8 *end = nullptr;
		const int n = DecompressKL4E(ours.data(), capacity, input.data(), input.size(), &end, !kl4e);
		if (n == KL4E_ERROR_INVALID_SIZE) {
			continue;  // The reference decoder would overrun its buffer here.
		}
		Bytes ref((size_t)capacity + (1 << 20), 0);
		const int m = decompress_kle(ref.data(), capacity, input.data(), nullptr, kl4e ? 1 : 0);
		compared++;
		CHECK_EQ(n, m);
		// On success and on failure alike, the same bytes were written.
		CHECK(memcmp(ours.data(), ref.data(), capacity) == 0);
		if (n >= 0) {
			ended++;
			produced += n;
		}
		if (n != m) {
			fprintf(stderr, "  seed %u: ours %d, reference %d\n", seed, n, m);
			break;
		}
	}
	CHECK(compared > 2500);
	CHECK(ended > 500);
	printf("  compared %d streams; %d ran to an end marker, %lld bytes between them\n", compared, ended, produced);
}

TEST(lzrc_roundtrip) {
	for (int variant = 0; variant < 24; variant++) {
		const u8 lc = (u8)(variant % 9);
		const Bytes data = variant & 1 ? PseudoRandom(1 + variant * 131, variant) : GenText(1 + variant * 87);
		const Bytes stream = LzrcEncodeLiterals(data, lc);
		Bytes out(data.size() + 16);
		int used = 0;
		const int n = DecompressLZRC(out.data(), (int)out.size(), stream.data() + 4, (int)stream.size() - 4, &used);
		CHECK_EQ(n, (int)data.size());
		CHECK(memcmp(out.data(), data.data(), data.size()) == 0);
		Bytes viaAny;
		std::string method, error;
		size_t consumed = 0;
		CHECK(DecompressAny(stream.data(), stream.size(), data.size(), &viaAny, &method, &consumed, &error));
		CHECK(viaAny == data);
	}
	// Stored mode.
	const Bytes data = PseudoRandom(40, 2);
	Bytes stream = { 0x80, 0, 0, 0, 40 };
	stream.insert(stream.end(), data.begin(), data.end());
	Bytes out(64);
	int used = 0;
	CHECK_EQ(DecompressLZRC(out.data(), 64, stream.data(), (int)stream.size(), &used), 40);
	CHECK(memcmp(out.data(), data.data(), 40) == 0);
	// Garbage fails cleanly (or decodes to something), never crashes.
	for (u32 seed = 0; seed < 200; seed++) {
		Bytes junk = PseudoRandom(256, seed);
		junk[0] &= 0x7F;
		Bytes o(4096);
		DecompressLZRC(o.data(), 4096, junk.data(), (int)junk.size(), &used);
	}
}
