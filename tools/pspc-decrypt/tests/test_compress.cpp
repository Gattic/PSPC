// The text kZlibDynamic and kGzipNamed hold. Same generator as the script that made them.
static Bytes GenText(size_t n) {
	static const char *const words[] = { "kirk", "psp", "allegrex", "flash0", "module", "prx", "decrypt", "elf", "psar", "m33", "\n", " " };
	u32 x = 12345;
	std::string out;
	while (out.size() < n) {
		x = (x * 1103515245u + 12345u) & 0x7fffffff;
		out += words[(x >> 16) % 12];
	}
	out.resize(n);
	return Bytes(out.begin(), out.end());
}

static Bytes Inflate(const u8 *data, size_t size, DeflateWrapper w, bool *ok, size_t *consumed = nullptr) {
	Bytes out;
	std::string error;
	size_t used = 0;
	*ok = InflateStream(data, size, w, &out, &used, &error);
	if (consumed) {
		*consumed = used;
	}
	return out;
}

TEST(inflate_python_vectors) {
	const std::string hello = "Hello, PSP! Hello, PSP! Hello, PSP!";
	const Bytes helloBytes(hello.begin(), hello.end());
	bool ok = false;
	size_t consumed = 0;
	CHECK(Inflate(kZlibStored, sizeof(kZlibStored), DeflateWrapper::Zlib, &ok, &consumed) == helloBytes);
	CHECK(ok);
	CHECK_EQ(consumed, sizeof(kZlibStored));
	CHECK(Inflate(kZlibFixed, sizeof(kZlibFixed), DeflateWrapper::Zlib, &ok) == helloBytes);
	CHECK(ok);
	const Bytes text = GenText(3000);
	CHECK_EQ(Sha1Hex(text.data(), text.size()), std::string("87363098e304a7c2589670d6eb3de698554a6036"));
	CHECK(Inflate(kZlibDynamic, sizeof(kZlibDynamic), DeflateWrapper::Zlib, &ok) == text);
	CHECK(ok);
	CHECK(Inflate(kGzipNamed, sizeof(kGzipNamed), DeflateWrapper::Gzip, &ok, &consumed) == Bytes(text.begin(), text.begin() + 1000));
	CHECK(ok);
	CHECK_EQ(consumed, sizeof(kGzipNamed));

	// Trailing data is left alone and reported through `consumed`.
	Bytes padded(kZlibDynamic, kZlibDynamic + sizeof(kZlibDynamic));
	padded.insert(padded.end(), 7, 0xAA);
	CHECK(Inflate(padded.data(), padded.size(), DeflateWrapper::Zlib, &ok, &consumed) == text);
	CHECK_EQ(consumed, sizeof(kZlibDynamic));
}

TEST(inflate_rejects_corruption) {
	bool ok = true;
	Bytes bad(kGzipNamed, kGzipNamed + sizeof(kGzipNamed));
	bad[bad.size() - 6] ^= 1;  // CRC
	Inflate(bad.data(), bad.size(), DeflateWrapper::Gzip, &ok);
	CHECK(!ok);
	bad.assign(kZlibDynamic, kZlibDynamic + sizeof(kZlibDynamic));
	bad[bad.size() - 1] ^= 1;  // Adler-32
	Inflate(bad.data(), bad.size(), DeflateWrapper::Zlib, &ok);
	CHECK(!ok);
	bad.assign(kZlibDynamic, kZlibDynamic + sizeof(kZlibDynamic) / 2);  // truncated
	Inflate(bad.data(), bad.size(), DeflateWrapper::Zlib, &ok);
	CHECK(!ok);
	// Random garbage must fail cleanly, never crash.
	for (u32 seed = 0; seed < 300; seed++) {
		Bytes junk = PseudoRandom(64 + seed, seed);
		junk[0] = 0x78;
		junk[1] = 0x9C;
		Inflate(junk.data(), junk.size(), DeflateWrapper::Zlib, &ok);
		CHECK(!ok);
	}
}

