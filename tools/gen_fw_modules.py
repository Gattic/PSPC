"""Writes data/fw_boot_modules.csv: the modules firmware 4.01 (with M33) has loaded by the time a
game's plugins start, in boot order, with the libraries each one exports and their NIDs.

pspc implements these modules natively. When M33 plugins are loaded it creates a record for each
(name, attributes, version) with an export table whose entries lead to its own implementations,
so plugins that look modules up by name and walk their exports (sceKernelFindModuleByName, then
ent_top) find what they would on a PSP.

Usage:
    python -I tools/gen_fw_modules.py [--inventory private/fw/401/inventory.json]
        [-o data/fw_boot_modules.csv]

The inventory comes from tools/fwinventory.py run over the extracted firmware (see
docs/firmware-tooling.md). Output lines:
    module,<name>,<attr>,<version>
    lib,<library>,<version>,<attr>,<nid> <nid> ...
"""

import argparse
import json
import os
import sys

# Game mode in pspbtcnf_02g.bin (mode mask 2), up to and including the user-mode kernel library;
# M33's SystemControl boots right after modulemgr.
BTCNF = 'flash0/kd/pspbtcnf_02g.bin'
GAME_MASK = 0x2
M33_AFTER = {'/kd/modulemgr.prx': 'm33/systemctrl_02g.prx'}
LAST = '/kd/usersystemlib.prx'


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--inventory', default='private/fw/401/inventory.json')
    ap.add_argument('-o', '--output', default='data/fw_boot_modules.csv')
    args = ap.parse_args()

    inv = json.load(open(args.inventory, encoding='utf-8'))
    files = {f['path']: f for f in inv['files']}
    btcnf = files.get(BTCNF)
    if not btcnf:
        sys.exit('%s: no %s' % (args.inventory, BTCNF))
    mode = next((m for m in btcnf['modes'] if int(m['mask'], 16) & GAME_MASK), None)
    if not mode:
        sys.exit('no game mode in %s' % BTCNF)

    order = []
    for p in mode['modules']:
        order.append('flash0' + p)
        if p in M33_AFTER:
            order.append(M33_AFTER[p])
        if p == LAST:
            break

    lines = ['# Generated by tools/gen_fw_modules.py from the 4.01 firmware inventory. Do not edit.',
             '# module,<name>,<attr>,<version>  then  lib,<library>,<version>,<attr>,<nids>']
    count = 0
    for path in order:
        f = files.get(path)
        mi = f.get('module_info') if f else None
        if not mi:
            print('skipping %s (not in the inventory)' % path, file=sys.stderr)
            continue
        major, minor = (int(x) for x in mi['version'].split('.'))
        lines.append('module,%s,%s,0x%04X' % (mi['name'], mi['attribute'], (major << 8) | minor))
        for lib in f.get('exports', []):
            if lib['library'] == 'syslib':
                continue
            nids = ' '.join(fn['nid'] for fn in lib['functions'])
            lines.append('lib,%s,%s,%s,%s' % (lib['library'], lib['version'], lib['attribute'], nids))
        count += 1
    os.makedirs(os.path.dirname(args.output) or '.', exist_ok=True)
    with open(args.output, 'w', encoding='utf-8', newline='\n') as out:
        out.write('\n'.join(lines) + '\n')
    print('%s: %d modules' % (args.output, count))


if __name__ == '__main__':
    main()
