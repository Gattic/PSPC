"""Convert data/nids.csv into the psplibdoc XML that pspdecompiler -n reads.

Usage:
    python -I tools/nids_to_psplibdoc.py data/nids.csv [-o data/psplibdoc.xml]

pspdecompiler's parser (reference/pspdecompiler/nids.c) is strict, so the
writer follows these rules:
  * element text is written verbatim on one line: names containing
    whitespace or XML-special characters (& < > " ') cannot be expressed
    and are skipped;
  * NIDs are written as 0x%08X with a lowercase "0x"; NID 0 is skipped;
  * a library's <NAME> precedes its FUNCTION entries;
  * every (library, NID) appears once (functions and variables share one
    NID space per library);
  * every FUNCTION carries <NUMARGS>-1</NUMARGS> (unknown).

The layout is one PRXFILE per library, which is valid psplibdoc and is also
accepted by prxtool and the Ghidra psplibdoc importers.
"""

import argparse
import csv
import os
import re
import sys
from collections import defaultdict

SAFE_NAME = re.compile(r"^[A-Za-z0-9_.$@:?\-]+$")


def main():
    ap = argparse.ArgumentParser(description="Convert nids.csv to psplibdoc XML.")
    ap.add_argument("csv", help="NID database (library,nid,name,source,hash_ok)")
    ap.add_argument("-o", "--out", default=os.path.join("data", "psplibdoc.xml"))
    args = ap.parse_args()

    libs = defaultdict(dict)
    skipped = defaultdict(int)
    with open(args.csv, newline="", encoding="utf-8") as f:
        for row in csv.DictReader(f):
            lib, name = row["library"].strip(), row["name"].strip()
            try:
                nid = int(row["nid"], 16)
            except ValueError:
                skipped["bad nid"] += 1
                continue
            if nid == 0:
                skipped["nid 0"] += 1
                continue
            if not lib or not SAFE_NAME.match(lib):
                skipped["bad library name"] += 1
                continue
            if not name or not SAFE_NAME.match(name):
                skipped["bad function name"] += 1
                continue
            if nid in libs[lib]:
                if libs[lib][nid] != name:
                    skipped["duplicate nid"] += 1
                continue
            libs[lib][nid] = name

    lines = ['<?xml version="1.0" encoding="UTF-8"?>',
             "<!-- Generated by tools/nids_to_psplibdoc.py from %s -->" % os.path.basename(args.csv),
             "<PSPLIBDOC>", "<PRXFILES>"]
    total = 0
    for lib in sorted(libs):
        lines += ["<PRXFILE>", "<PRX>unknown</PRX>", "<PRXNAME>%s</PRXNAME>" % lib,
                  "<LIBRARIES>", "<LIBRARY>", "<NAME>%s</NAME>" % lib, "<FUNCTIONS>"]
        for nid in sorted(libs[lib]):
            lines.append("<FUNCTION><NID>0x%08X</NID><NAME>%s</NAME><NUMARGS>-1</NUMARGS></FUNCTION>"
                         % (nid, libs[lib][nid]))
            total += 1
        lines += ["</FUNCTIONS>", "</LIBRARY>", "</LIBRARIES>", "</PRXFILE>"]
    lines += ["</PRXFILES>", "</PSPLIBDOC>"]
    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    with open(args.out, "w", newline="\n", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote %s: %d libraries, %d NIDs" % (args.out, len(libs), total))
    for k, v in sorted(skipped.items()):
        print("  skipped %d (%s)" % (v, k), file=sys.stderr)


if __name__ == "__main__":
    main()
